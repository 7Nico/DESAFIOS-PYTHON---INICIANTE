#Desenvolva um progrma aque leia as duas notas de um aluno, calcule e mostre a sua média.

print('====== DESAFIO 07 ======')
n1 = float(input('Qual foi a nota de sua primeira prova?'))
n2 = float(input('Qual foi a nota de sua segunda prova?'))
